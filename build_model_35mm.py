from pathlib import Path
import json, zipfile, xml.etree.ElementTree as ET
import cv2
import numpy as np
from PIL import Image
from shapely.geometry import Polygon, MultiPolygon
from shapely import affinity
from shapely.ops import unary_union
import trimesh
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.path import Path as MPath
from matplotlib.patches import PathPatch, Rectangle
from mpl_toolkits.mplot3d.art3d import Poly3DCollection

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'BOSS_cube_35mm'
OUT.mkdir(exist_ok=True)
SIDE, LOGO_WIDTH, RELIEF = 35.0, 28.0, 0.8
NS = 'http://schemas.microsoft.com/3dmanufacturing/core/2015/02'
ET.register_namespace('', NS)

def extract():
    rgb = np.array(Image.open(ROOT/'images.jpg').convert('RGB'))
    bg = np.median(rgb[10:20, 20:128].reshape(-1,3),axis=0).astype(int)
    cyan = '#'+''.join(f'{v:02X}' for v in bg)
    # White ink is separated from cyan by its red channel. Use interpolation
    # and a subpixel contour, not a substituted font or square pixel voxels.
    up = 8
    red = cv2.resize(rgb[:,:,0],None,fx=up,fy=up,interpolation=cv2.INTER_CUBIC)
    red = cv2.GaussianBlur(red,(0,0),3.2)
    threshold = (float(bg[0]) + 250) / 2
    mask = (red > threshold).astype('uint8')*255
    margin = 10*up
    mask[:margin,:]=0; mask[-margin:,:]=0
    mask[:,:margin]=0; mask[:,-margin:]=0
    contours, hierarchy = cv2.findContours(mask,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_SIMPLE)
    hierarchy=hierarchy[0]
    def ring(c):
        pts=cv2.approxPolyDP(c,0.13*up,True)[:,0,:].astype(float)/up
        pts[:,1]*=-1
        return pts
    polygons=[]
    for i,c in enumerate(contours):
        if hierarchy[i,3]!=-1 or cv2.contourArea(c)<2*up*up:
            continue
        holes=[]
        child=hierarchy[i,2]
        while child!=-1:
            if cv2.contourArea(contours[child])>up*up:
                holes.append(ring(contours[child]))
            child=hierarchy[child,0]
        p=Polygon(ring(c),holes)
        assert p.is_valid, 'Invalid extracted outline'
        polygons.append(p)
    ink=unary_union(polygons)
    x0,y0,x1,y1=ink.bounds
    factor=LOGO_WIDTH/(x1-x0)
    ink=affinity.translate(ink,-(x0+x1)/2,-(y0+y1)/2)
    ink=affinity.scale(ink,xfact=factor,yfact=factor,origin=(0,0))
    return list(ink.geoms) if isinstance(ink,MultiPolygon) else [ink],cyan

def mesh_element(resources,mesh,oid,name,index):
    obj=ET.SubElement(resources,'object',id=str(oid),type='model',name=name,pid='4',pindex=str(index))
    geom=ET.SubElement(obj,'mesh')
    vs=ET.SubElement(geom,'vertices')
    for p in mesh.vertices:
        ET.SubElement(vs,'vertex',**dict(zip(('x','y','z'),(f'{v:.7f}' for v in p))))
    ts=ET.SubElement(geom,'triangles')
    for f in mesh.faces:
        ET.SubElement(ts,'triangle',pid='4',p1=str(index),p2=str(index),p3=str(index),**dict(zip(('v1','v2','v3'),map(str,f))))

def xml(el):
    return ET.tostring(el,encoding='utf-8',xml_declaration=True)

def export_3mf(body,text,cyan):
    model=ET.Element('model',{'xmlns':NS,'unit':'millimeter','xml:lang':'en-US','xmlns:m':'http://schemas.microsoft.com/3dmanufacturing/material/2015/02','xmlns:BambuStudio':'http://schemas.bambulab.com/package/2021'})
    ET.SubElement(model,'metadata',name='Application').text='BOSS Cube Model Builder 1.0'
    ET.SubElement(model,'metadata',name='BambuStudio:3mfVersion').text='1'
    ET.SubElement(model,'metadata',name='Title').text='BOSS cube 35mm - cyan body, white raised lettering'
    ET.SubElement(model,'metadata',name='Description').text='Geometry only; choose your printer and material presets. Generated by build_model.py.'
    resources=ET.SubElement(model,'resources')
    mats=ET.SubElement(resources,'m:colorgroup',id='4')
    ET.SubElement(mats,'m:color',color=cyan+'FF')
    ET.SubElement(mats,'m:color',color='#FFFFFFFF')
    mesh_element(resources,body,1,'Cyan body - filament 1',0)
    mesh_element(resources,text,2,'White BOSS lettering - filament 2',1)
    assembly=ET.SubElement(resources,'object',id='3',type='model',name='BOSS cube 35mm')
    comps=ET.SubElement(assembly,'components')
    ET.SubElement(comps,'component',objectid='1')
    ET.SubElement(comps,'component',objectid='2')
    build=ET.SubElement(model,'build')
    ET.SubElement(build,'item',objectid='3',transform='1 0 0 0 1 0 0 0 1 90 90 0',printable='1')
    cfg=ET.Element('config')
    obj=ET.SubElement(cfg,'object',id='3')
    ET.SubElement(obj,'metadata',key='name',value='BOSS cube 35mm')
    ET.SubElement(obj,'metadata',key='extruder',value='1')
    for oid,name,extruder in [(1,'Cyan body',1),(2,'White BOSS lettering',2)]:
        part=ET.SubElement(obj,'part',id=str(oid),subtype='normal_part')
        ET.SubElement(part,'metadata',key='name',value=name)
        ET.SubElement(part,'metadata',key='extruder',value=str(extruder))
    plate=ET.SubElement(cfg,'plate')
    ET.SubElement(plate,'metadata',key='plater_id',value='1')
    ET.SubElement(plate,'metadata',key='plater_name',value='BOSS cube')
    ET.SubElement(plate,'metadata',key='locked',value='false')
    inst=ET.SubElement(plate,'model_instance')
    ET.SubElement(inst,'metadata',key='object_id',value='3')
    ET.SubElement(inst,'metadata',key='instance_id',value='0')
    ET.SubElement(inst,'metadata',key='identify_id',value='1')
    content_types='''<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/><Default Extension="config" ContentType="application/octet-stream"/></Types>'''
    rels='''<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>'''
    with zipfile.ZipFile(OUT/'BOSS_cube_35mm.3mf','w',zipfile.ZIP_DEFLATED) as z:
        z.writestr('[Content_Types].xml',content_types)
        z.writestr('_rels/.rels',rels)
        z.writestr('3D/3dmodel.model',xml(model))
        z.writestr('Metadata/model_settings.config',xml(cfg))

def render(polys,body,letters,cyan):
    fig=plt.figure(figsize=(12,7),facecolor='#F4F6F8')
    ax=fig.add_axes([0.02,0.14,0.46,0.74],projection='3d',facecolor='#F4F6F8',computed_zorder=False)
    # Explicit collection order avoids mplot3d's average-depth occlusion of
    # small lettering by the cube's much larger top-face triangles.
    elev,azim=np.radians([38,-68])
    camera=np.array([np.cos(elev)*np.cos(azim),np.cos(elev)*np.sin(azim),np.sin(elev)])
    for mesh,color,order in [(body,cyan,1),(letters,'#FFFFFF',2)]:
        visible=mesh.triangles[(mesh.face_normals@camera)>1e-7]
        ax.add_collection3d(Poly3DCollection(visible,facecolors=color,linewidths=0,antialiaseds=False,shade=True,zorder=order,lightsource=matplotlib.colors.LightSource(azdeg=300,altdeg=60)))
    ax.set(xlim=(-22.4,22.4),ylim=(-22.4,22.4),zlim=(-2.8,42))
    ax.set_box_aspect((1,1,1)); ax.view_init(elev=38,azim=-68)
    ax.set_proj_type('ortho'); ax.set_axis_off()
    front=fig.add_axes([0.55,0.19,0.38,0.65],facecolor='#F4F6F8')
    front.add_patch(Rectangle((-17.5,-17.5),35,35,facecolor=cyan))
    from shapely.geometry.polygon import orient
    for p in polys:
        p=orient(p,sign=1)
        points=[];codes=[]
        for ring in [p.exterior,*p.interiors]:
            coords=list(ring.coords)
            points.extend(coords); codes.extend([MPath.MOVETO]+[MPath.LINETO]*(len(coords)-2)+[MPath.CLOSEPOLY])
        front.add_patch(PathPatch(MPath(points,codes),facecolor='white',edgecolor='none'))
    front.set(xlim=(-18.9,18.9),ylim=(-18.9,18.9)); front.set_aspect('equal');front.axis('off')
    fig.text(.07,.91,'BOSS / 35 mm',fontsize=24,color='#1E3542',weight='bold')
    fig.text(.57,.89,'LOGO FACE',fontsize=12,color='#506574')
    fig.text(.07,.09,'35 x 35 x 35 mm body   /   0.8 mm raised lettering',fontsize=12,color='#506574')
    fig.text(.07,.05,'Cyan + white   |   Logo face upward for printing',fontsize=11,color='#506574')
    fig.savefig(OUT/'preview.png',dpi=160,facecolor=fig.get_facecolor())
    plt.close(fig)

def main():
    polys,cyan=extract()
    body=trimesh.creation.box(extents=[SIDE,SIDE,SIDE]);body.apply_translation([0,0,SIDE/2])
    pieces=[]
    for p in polys:
        piece=trimesh.creation.extrude_polygon(p,RELIEF,engine='earcut')
        piece.apply_translation([0,0,SIDE]);pieces.append(piece)
    lettering=trimesh.util.concatenate(pieces)
    for mesh in [body,lettering,*pieces]:
        assert mesh.is_watertight and mesh.is_winding_consistent and mesh.volume>0
    assert np.allclose(body.extents,[SIDE,SIDE,SIDE])
    assert np.isclose(lettering.bounds[0,2],SIDE) and np.isclose(lettering.bounds[1,2],SIDE+RELIEF)
    assert np.isclose(lettering.extents[0],LOGO_WIDTH)
    assert all(Polygon([(-SIDE/2,-SIDE/2),(SIDE/2,-SIDE/2),(SIDE/2,SIDE/2),(-SIDE/2,SIDE/2)]).contains(p) for p in polys)
    body.export(OUT/'body_cyan.stl');lettering.export(OUT/'lettering_white.stl')
    export_3mf(body,lettering,cyan)
    render(polys,body,lettering,cyan)
    report={'body_mm':body.extents.tolist(),'overall_mm':[SIDE,SIDE,SIDE+RELIEF],'lettering_mm':lettering.extents.tolist(),'lettering_parts':len(pieces),'lettering_holes':sum(len(p.interiors) for p in polys),'cyan_hex':cyan,'body_volume_mm3':body.volume,'lettering_volume_mm3':lettering.volume,'all_meshes_watertight':True,'all_meshes_consistently_oriented':True,'contact_plane_mm':SIDE,'lettering_fully_supported':True,'faces':len(lettering.faces)+len(body.faces),'printer_profile_embedded':False}
    (OUT/'geometry_validation.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    (OUT/'lettering_outline.json').write_text(json.dumps([{'outer':list(p.exterior.coords),'holes':[list(r.coords) for r in p.interiors]} for p in polys],indent=2),encoding='utf-8')
    print(json.dumps(report,indent=2))

if __name__=='__main__': main()
